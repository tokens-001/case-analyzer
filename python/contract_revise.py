"""按分析结果列一份**改动对照表** —— 每一条：这一款原来怎么写 → 建议改成什么。

🔴 **为什么这里没有"自动改好的合同"**（2026-09-28，本来做了、验完删掉了）：

第一版按「把摘录换成改法文字」机械替换，跑真机数据当场露馅 ——
输出的合同里**同一句话出现两遍**：

    2、乙方违反本合同约定、…经济损失的，乙方违反本合同约定、…经济损失的，
       应当赔偿甲方的直接经济损失及…

**根因是分析输出本身的格式不匹配**（拿真机 11 条量过）：

    · 「摘录」只有 **17~30 字**，而它所在的那一行 **50~107 字** ⇒ 摘录只是行里一小截；
    · 「改成」有 **115~179 字**，是**整条重写**（连开头都重写了）；
    · 还有 2/12 条连定位都不唯一（1 条字面找不到、1 条命中两行）。

⇒ **拿"一小截"去换"一整条"，开头必然重复。** 这不是装配器能修的，是**两边格式对不上**：
`摘录` 的作用是**指到哪儿**，`改成` 是**那条该长成什么样**。

⚠️ **我第一版验错了东西**：跑了个"12/12 字面命中"就下结论说"可行" ——
验的是**找不找得到**，不是**改完读不读得通**。

⇒ 要真出"修订版"，得先把提示词改成"**「改成」只写替换「摘录」那一段**"，
   而那要重跑一轮才知道模型照不照做（提示词改动的效果没法离线证明）。
   **在那之前，只出对照表** —— 人照着它自己改，比给一份读不通的合同安全。

🔵 对照表的「原文」取的是**摘录所在的那一整行**（不是那 17 字）——
   不然「原文 → 改成」看着像"改一点变成一大段"，对不上。
   定位不唯一的那几条退回用摘录，并**明说没定位准**。
"""
from __future__ import annotations

import re

from report_render import 合并, _重线, _分隔, _节, _净, _缩, _分段

def _找那一行(原文: str, 摘录: str) -> tuple[str, bool]:
    """摘录落在哪一行 → `(那一行的全文, 定位唯一吗)`。

    🔴 **必须认 `……`**：提示词里 `引用格式要求` 明写「摘录必须能逐字找到
    （**中间可用……省略**）」⇒ 摘录常常是「甲方……有权合理调整乙方工资待遇」这种
    带省略的写法。拿整串做 `in` 检查，**带省略号的一条都定位不到**
    （第一版就是这么把第四条第4款判成"没定位"的）。
    ⇒ 按 `……` 切开，**每一段都落在同一行**才算命中。

    ⚠️ 找不到或命中多行 ⇒ 退回用摘录本身，并**如实标"没定位准"** ——
    编一个"看着像"的原文出来，比说"我定位不了"坏得多。
    """
    片 = [x.strip() for x in re.split(r"[…]{2,}|\.{3,}", 摘录 or "") if x.strip()]
    if not 片:
        return 摘录, False
    命中 = [l for l in (原文 or "").splitlines() if all(x in l for x in 片)]
    if len(命中) == 1:
        return 命中[0].strip(), True
    return 摘录, False


def 对照(送检文本: str, 数据: dict) -> dict:
    """→ `{"对照": [...], "新增": [...], "没定位": n}`"""
    合 = 合并(数据)
    条目: list[dict] = []
    没定位 = 0
    for 号, 条 in 合["按条款"].items():
        摘 = (条.get("摘录") or "").strip()
        if not 摘:
            continue
        原, 准 = _找那一行(送检文本, 摘)
        没定位 += (not 准)
        为什么 = (条.get("正文") or "").strip()
        if 为什么.startswith(("风险", "问题")):
            为什么 = 为什么[2:].lstrip("：:")
        条目.append({"号": 号, "原": 原, "摘录": 摘, "定位准": 准,
                     "改": (条.get("改法") or "").strip(),
                     "为什么": 为什么, "依据": (条.get("依据") or "").strip()})

    新增 = []
    for _档, _号, 段 in 合["补什么"]:
        m = re.search(r"条款文字[：:]\s*「(.+?)」", 段, re.S)
        风险 = re.search(r"补什么风险[：:]\s*(.+?)(?=\n条款文字|$)", 段, re.S)
        if m:
            新增.append({"文字": m.group(1).strip(),
                         "补什么": (风险.group(1).strip() if 风险 else "")})
    return {"对照": 条目, "新增": 新增, "没定位": 没定位}


def 渲染对照表(送检文本: str, 数据: dict) -> str:
    """改在哪、为什么改、补什么 —— 人照着它自己动手改合同。**纯文本**，见 `report_render` 的版式那一节。"""
    名称 = (数据.get("判例名") or "未命名").strip()
    果 = 对照(送检文本, 数据)
    改的 = [c for c in 果["对照"] if c["改"]]
    出 = [_重线, "   改动对照表", f"   {名称}", _重线, "",
          f"   要改 {len(改的)} 处"
          + (f" · 建议新增 {len(果['新增'])} 条" if 果["新增"] else "")
          + (f" · ⚠️ {果['没定位']} 处没能定位到原文" if 果["没定位"] else ""), ""]
    立场 = str(数据.get("立场") or "").strip()
    if 立场:
        出.append("   立场        " + ("中立（不预设你是哪一方）" if 立场 == "中立"
                                      else f"站在【{立场}】角度"))
    出 += ["", "   这一份是给你照着改合同的。每一条都能在原文里找到出处；",
           "   定位不准的那几处会明说，不会编一个看着像的给你。", ""]

    for i, c in enumerate(改的, 1):
        出 += _节(f"{i}/{len(改的)}　{c['号']}")
        出 += ["      原  文"] + _缩(_净(c["原"]), 6).splitlines() + [""]
        if not c["定位准"]:
            出 += _缩(f"⚠️ 摘录「{c['摘录']}」在原文里没能唯一定位"
                     f"（找不到、或出现多次）—— 请自己对一下是不是这一处。", 6).splitlines() + [""]
        出 += ["      改 成"] + _缩(_净(c["改"]), 6).splitlines() + [""]
        if c["为什么"]:
            出 += ["      为什么"] + _缩(_净(_分段(c["为什么"])), 6).splitlines() + [""]
        if c["依据"]:
            出 += ["      依  据"] + _缩(_净(c["依据"]), 6).splitlines() + [""]

    if 果["新增"]:
        出 += _节("建议新增的条款")
        出 += ["   下面这些是合同里现在没有的文字，条号请自己排进去。", ""]
        for i, n in enumerate(果["新增"], 1):
            出 += ["", f"  ● 新增 {i}"]
            if n["补什么"]:
                出 += ["", "      补什么风险"] + _缩(_净(n["补什么"]), 6).splitlines()
            if n["文字"]:
                出 += ["", "      条款文字"] + _缩(_净(n["文字"]), 6).splitlines()
            出.append("")

    出 += ["", _重线, "",
           "  这是分析结果的整理，不是法律意见；没有判断改完的法律效果。",
           "  动笔之前，请找执业律师把这份对照表过一遍。", ""]
    return "\n".join(出) + "\n"
