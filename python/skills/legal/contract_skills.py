"""合同审查技能组（站我方：风险 → 改法 → 谈判顺序）。

与判决书/案情模式不同的两点，都是有意的：
1. **所有维度放在一个模块**，而不是一个技能一个文件。它们共用同一套约束
   （我方立场、逐条锚点格式、必查表），拆成七个文件就是把同一份提示词抄七遍 ——
   抄过一遍的都知道会漂。
2. **每个维度都要求逐条挂合同原文**，格式由 `verify_clauses.引用格式要求` 给出
   （`改法建议` 用 `改法格式要求`，它多一段拟稿文字，校验只吃分界之前那半段），
   本地校验按同一份格式反查。模型不守格式时，读数落到「未校验」而不是「通过」。

调用顺序（`app.py:分析路由` 的合同分支）：前四维并行 → 改法建议 → 谈判顺序 → 总结。
后三维必须串行，因为它们各自的提示词都写着"把上面几类……"。

依赖：DeepSeek API（_base.问AI）。本模块不做任何真实性判断。
"""

from ._base import 问AI
from .contract_types import 必查清单
from .verify_clauses import 引用格式要求, 改法格式要求

#: 「我方是哪一方」—— **由用户在界面上选**（2026-09-28），默认"中立"。
#:
#: 🔴 **为什么不能再写死**：原来这里是一个常量（"我方＝签字/付款/接受服务的一方"），
#: 后果有两层，第二层才是真问题：
#:  ① 模型可以推翻它而不受约束 —— 真机上它对一份**劳动合同**站了**乙方**，
#:     而按那条规则本该站**甲方**（甲方＝发工资的付款方＋接受劳动的一方）；
#:  ② 🔴 **它推翻了也从不告诉任何人它站了哪边** —— 那份报告里「我方」出现 **52 次**，
#:     而交代立场的说法**一次都没有**。收件人读「对我方明显不利」得自己猜"我方"是谁，
#:     **猜反了整份报告的意思就反过来，而它通篇看不出**（见 `~/OPEN.md`）。
#: ⇒ 立场必须是**用户说了算的输入**，并且**写进报告**（`app.py` 的 `立场` 元数据字段）。
#:
#: ⚠️ **没有"由工具判断"这一档**，是有意的：它就是这个 bug 的产地。
#: 选不出来的时候默认**中立**（不站边最安全），而不是回到"让它自己猜"。
_视角表 = {
    "甲方": ("你替【我方】审这份合同，**我方是甲方**。"
             "只报对甲方不利、或对甲方保护不足的点；乙方纯获利但甲方可接受的常规条款不必纠缠。"),
    "乙方": ("你替【我方】审这份合同，**我方是乙方**。"
             "只报对乙方不利、或对乙方保护不足的点；甲方纯获利但乙方可接受的常规条款不必纠缠。"),
    # 中立这一档要**重新定义【我方】这个词**：下面八个维度的任务句里全都写着它。
    # 与其把那八句各改三遍（改漏一句就自相矛盾），不如在这里一次说清"本报告里它读作什么"。
    "中立": ("你审这份合同，**不预设你是哪一方**（本报告不设「我方」）。"
             "下文所有「对我方不利 / 对我方保护不足」一律读作「**对合同某一方不利**」。"
             "只报这两类：① 法律有强制规定而这里没写、或写法可能违法的；"
             "② 无论站哪一边都失衡的（一方只有权利、另一方只有义务）。"
             "⚠️ 不要写「建议我方争取」这种**只有站边才成立**的话。"),
}
默认视角 = "中立"


def 规范视角(视角: str = "") -> str:
    """把用户给的值收成**表里真有的那一档**；认不出 ⇒ 中立。

    🔴 **必须有这个函数，不能各处各写一份 `or 默认视角`**（2026-09-28 被测试当场抓到）：
    路由原来直接把 `data.get("side")` 当结果用 ⇒ 传 `"原告"` 时**提示词落回了中立，
    而回给前端/存进报告的却是「原告」** —— 报告声称的立场和模型实际用的**不是一个东西**。
    这正是这条链路上最坏的一种错：**报告说 A，报告内容是按 B 生成的**。
    ⇒ 一处规范化，`立场文本` 和 `报告里的立场` 都读它，不可能再分叉。
    """
    s = str(视角 or "").strip()
    return s if s in _视角表 else 默认视角


def 立场文本(视角: str = "") -> str:
    """这一轮用的立场段。**取不到就落回中立**（不落回"让它自己猜" —— 那正是要修的）。"""
    return _视角表[规范视角(视角)]

底线 = ("只依据合同文本本身说话：不臆测签约背景、不补写合同里没有的约定、"
        "不假设已发生的履行事实。原文找不到的内容，就当它不存在。")

依据要求 = (
    "每条结论末尾用「依据：」注明它站在哪儿，二选一：\n"
    "  · 法律有明文 —— 写《法律名》第N条（这条会拿去跟法条库逐字核对，核不到就标未校验）\n"
    "  · 法律没有强制、只是对你不利 —— 写「依据：实务判断（法律未强制）」\n"
    "把后者写成前者，等于给一条不存在的法条背书；把前者写成后者，"
    "等于白让你本来站得住的那一步。这一区分比措辞漂亮重要。")

格式 = ("输出格式（硬性要求）：\n" + 引用格式要求 + "\n" + 依据要求 +
        "\n确实一条都写不出时，只回一行：未发现可指认的问题。不要为凑数编造引用。")

改法格式 = ("输出格式（硬性要求）：\n" + 改法格式要求 +
            "\n确实一条都写不出时，只回一行：未发现可指认的问题。不要为凑数编造引用。")


def _提示(任务, 合同文本, 类型, 额外="", 格式要求=格式, 视角=""):
    必查 = ""
    if 类型:
        必查 = (f"\n本合同类型「{类型}」的必查条款清单：\n"
                + "\n".join(f"- {x}" for x in 必查清单(类型)))
    return (f"{任务}\n\n{立场文本(视角)}\n{底线}{必查}{额外}\n\n{格式要求}\n\n合同全文：\n{合同文本}")


def 风险清单(合同文本, 类型, api_key, 视角=""):
    return 问AI(_提示("逐条列出对我方的风险，按危害大小排序，最多 12 条；每条三行以内：引的原文、为什么对我方不利、依据。不要为了省字把后两行省掉。",
                      合同文本, 类型, 视角=视角), 合同文本, api_key, 附段落编号=False)


def 缺失条款(合同文本, 类型, api_key, 视角=""):
    return 问AI(_提示("对照上面的必查清单，逐项判断合同里【有没有】相应约定。每项一行，先说它是法定必备还是建议约定（照清单上标的写，别自己升格或降格）。"
                      "只列缺失或明显不完整的那几项；每项要指出它应当出现在哪一条里"
                      "（可写「建议新增第X条」），并说明缺了它对我方的具体后果。",
                      合同文本, 类型, 视角=视角), 合同文本, api_key, 附段落编号=False)


def 失衡条款(合同文本, 类型, api_key, 视角=""):
    return 问AI(_提示("找权利义务不对等的条款：只约束我方不约束对方的义务、违约金或赔偿上限悬殊、"
                      "单方变更权、单方解除权、对方免责范围过宽、付款与交付时点错配。",
                      合同文本, 类型, 视角=视角), 合同文本, api_key, 附段落编号=False)


def 歧义表述(合同文本, 类型, api_key, 视角=""):
    return 问AI(_提示("找写了但无法执行的条款：没有标准、没有时限、没有主体、数值口径不明"
                      "（如「合理期限」「相关费用」「视情况而定」），"
                      "以及同一事项前后条款互相矛盾之处。", 合同文本, 类型, 视角=视角), 合同文本, api_key, 附段落编号=False)


def 改法建议(合同文本, 类型, api_key, 已有=None, 视角=""):
    """把已经指认的问题，逐条写成**可以直接替换进合同的条款文字**。

    为什么要它：普通人看完"第9条单方调岗对你不利"，下一句一定是"那改成什么样"。
    原来只有 `谈判顺序` 里一句"给一句可以直接写进回复的话术"，零散且不成体系。

    为什么它仍然可核验：每条前半段照 `引用格式要求` 摘原文，本地校验只查那半段；
    "改成："后面是拟稿，按定义不该在合同里找得到，所以 `verify_clauses.建议分隔`
    把校验范围切在分界之前 —— 否则就是对着正确输出亮红牌。
    """
    问题 = _已有段(已有)
    return 问AI(_提示(
        "把上面已经指认的问题逐条改写成可以直接替换进合同的条款文字。最多 12 条；条款文字本身可以长，别压成一句概括 —— 压了就贴不进合同。"
        "一条问题一行，改动要能真正修掉那个风险，不是把原话换个说法。"
        "需要具体数额、期限而合同里没有的，写成「＿＿」并注明由双方填写，"
        "**不要替当事人编一个数字**。",
        合同文本, 类型, 额外="\n这一维只处理上面**挂着合同条号**的问题；"
                              "『合同里根本没有这条』（缺失条款）不要出现在这里。" + 问题,
        格式要求=改法格式 + "\n" + 依据要求, 视角=视角), 合同文本, api_key, 附段落编号=False)


def 新增条款(合同文本, 类型, api_key, 已有=None, 视角=""):
    """给『合同里根本没有』的那几项，写出可以直接整条贴进去的文字。

    为什么不并进 `改法建议`：那一维的每条都靠"前半段是原文摘录"来接受逐字回查，
    而这里**没有原文可摘** —— 混在一起，模型要么漏锚点（被判未校验），
    要么为了守格式**编一条锚点**（被判疑似编造）。两种都是拿错判据去量对的东西。

    所以这一维刻意不进 `verify_clause_anchors`（见 `app.py:分析路由` 的 锚点范围），
    但它引的法条照样过 `classify_law_citations` —— 可核验的范围变了，不是没了。
    """
    return 问AI(_提示(
        "针对上面指出的『合同里缺失』的每一项，写一条可以整条贴进合同的完整条款文字。"
        "一条缺失一项，按重要度排序；每条前面用一行说明它补的是什么风险。"
        "需要数额、期限而合同里没有的，写成「＿＿」并注明由双方填写，不要替当事人编一个数字。",
        合同文本, 类型,
        额外="\n只处理**合同里现在没有**的内容。已有条款要改的不在这里（那是改法建议那一维）。"
             "\n不要写【第N条】式的锚点 —— 这一维没有原文可摘，写了会被当成你对现有合同的引用。"
             "\n条号请写成「建议新增第X条」，由当事人自己排到合同里。" + _已有段(已有),
        视角=视角,
        格式要求=("输出格式：每条两行 ——\n"
                  "补什么风险：一句话\n"
                  "条款文字：「可以直接粘贴的完整条款」\n"
                  "不要求也不该能在现合同里找到；确实没有要补的，只回一行：未发现必须新增的条款。")),
        合同文本, api_key, 附段落编号=False)


def 谈判顺序(合同文本, 类型, api_key, 已有=None, 视角=""):
    """把前几类的结论收成一份谈判清单，排在 `改法建议` 之后。

    `已有` = 前面各维的**实际输出**。原来这一维和前四维并行发出，提示词却写着
    "把上面几类问题收成一份谈判清单" —— 那时"上面"还是空的，它只能对着合同原文
    另拟一套，于是这份清单和报告里的风险清单各说各话。要么喂进真实结论，
    要么别声称在汇总它们。
    """
    return 问AI(_提示("把上面几类问题收成一份谈判清单：按「我方收益 ÷ 对方让步成本」排序，"
                      "分三档：必须改（不改就不该签）/ 力争改 / 可接受但留记录。"
                      "每条只写：条号 + 一句话为什么重要 + 用哪一份改法文字去提，"
                      "**不要另拟一版条款文字**（改法那一维已经给过了，两版不一致会打架）。",
                      合同文本, 类型,
                      额外="\n这一份是给谈判桌上用的，不复述风险细节，也不重写条款。"
                           + _已有段(已有), 视角=视角), 合同文本, api_key, 附段落编号=False)


def _已有段(已有):
    if not 已有:
        return ""
    return ("\n\n已查出的问题（按这些排，不要另起一套）：\n" + "\n\n".join(
        f"【{名}】\n{文}" for 名, 文 in 已有.items() if 文))


def 总结(合同文本, 类型, 各维度, api_key, 视角=""):
    已有 = "\n\n".join(f"【{名}】\n{文}" for 名, 文 in 各维度.items())
    return 问AI(
        f"基于以下七个维度的审查结果，给我方一段结论，分三部分、按序号写：\n"
        f"1. 能不能签：整体风险量级（低/中/高）与理由。\n"
        f"2. 签之前必须先解决哪两三件事 —— 从上面「必须改」那一档里挑，写清是第几条。\n"
        # 第 3 部分是整个工具最该给出的东西：前七维都在说"哪里有问题"，
        # 只有这里能回答"那我该怎么办"。原来只有前两部分，用户拿到
        # 「不改就不该签」这种结论后没有下一步 —— 等于把最难的决定丢给他就走了。
        f"3. 如果对方在这几件事上就是不让步，你的**退路**是什么。\n"
        f"   必须具体到「你下一步做什么」。只写真的适用的，从这些里挑："
        f"不签这一份 / 换一家 / 先不付定金或首付款 / 要求把对方的口头承诺写进合同再签 / "
        f"拿这几条去问一次执业律师 / 接受但对某项要一个书面承诺。\n"
        f"   不许写「建议协商」「注意风险」「保持沟通」这类听着对、做不了的空话。\n"
        f"不重复细节，不超过 350 字。\n{立场文本(视角)}\n{底线}\n\n{已有}",
        合同文本, api_key, 附段落编号=False)
