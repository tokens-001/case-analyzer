# ⚠️ 法名长度上限原来是 20 字，实测把**最常用的那几条司法解释整条吞掉**：
#   《最高人民法院关于审理民间借贷案件适用法律若干问题的规定》(27字)
#   《最高人民法院关于适用〈中华人民共和国民法典〉时间效力的若干规定》(31字)
# 吞掉的后果不是"少校验一条"，是它**连未校验数都不进** —— 静默逃逸，
# 而本页的绿灯于是覆盖到一个谁都没看见的引用上。放宽到 40（司法解释全名的实际上限）。
法条正则 = r'(?:《[^》]{2,40}》|[^\s，。；]{2,10}[法典])\s*第\s*[一二三四五六七八九十百千\d]+\s*(?:条(?:\s*之\s*[一二三四五六七八九十]+)?)?'

# 只写了法名、没给条号的援引（"依据《民法典》合同编的有关规定…"）。
# 这类串**结构上无法校验** —— 上面那条正则要求出现"第…条"，所以它压根不进提取集合。
# 单独抓出来计数，是为了让"通过校验"这四个字只覆盖真被校验过的东西。
法名正则 = r'《[^》]{2,40}》'
条号后缀 = re.compile(r'\s*第\s*[一二三四五六七八九十百千\d]+\s*条')

# "参照本法第七百九十三条"这种**相对指代**：法名正则会把它当成一部法（"参照本法"），
# 于是被判成"库里没这部法"、写进补库清单 —— 可"本法"根本没法补进库。
# 它属于"无从校验"，不是"覆盖不足"。
相对指代词 = ("本法", "该法", "前述", "上述", "前条", "后条")


def _是相对指代(引用, 法名):
    if "《" in 引用:
        return False          # 带书名号的是正式引用，不走这条路
    return any(法名.endswith(w) for w in 相对指代词)

def _提取法条引用(文字):
    return list(set(re.findall(法条正则, 文字)))



def _解析法条元数据(文件路径):
    """从法条文件中提取#META...#END元数据块"""
    try:
        with open(文件路径, "r") as f:
            内容 = f.read()
        元数据匹配 = re.search(r'#META\n(.*?)\n#END', 内容, re.DOTALL)
        if not 元数据匹配:
            return {}
        元数据 = {}
        for 行 in 元数据匹配.group(1).split("\n"):
            if ":" in 行:
                键, 值 = 行.split(":", 1)
                元数据[键.strip()] = 值.strip()
        return 元数据
    except Exception:
        return {}


