# Skill 1: 法条引用统计
# ═══════════════════════════════════════════════════════════

def count_law_citations(*分析列表):
    """统计AI分析中引用了多少条法律条文"""
    合并 = " ".join(分析列表)
    法条集合 = sorted(set(_提取法条引用(合并)))
    if 法条集合:
        列出 = 法条集合[:5]
        余 = len(法条集合) - len(列出)
        return f"引用法条 {len(法条集合)} 条：" + "、".join(列出) + (f"…（另有 {余} 条未列出）" if 余 else "")
    return "未引用法律条文"


# ═══════════════════════════════════════════════════════════
# Skill 2: 法条三态校验 —— 本模块唯一的判据出口
# ═══════════════════════════════════════════════════════════

def _读取法条库(法条库目录):
    """把库里的法条文本一次读进内存 {文件名: 全文}。

    原来两条查库的路径各自反复读盘：`verify_law_citation_realness` 在
    "引用 × 候选文件"的双层循环里对同一份文件 `open().read()` 好几遍，
    `search_law_database` 又自己走一遍。合并成一次读盘、一次判定。
    """
    全文表 = {}
    for 文件名 in os.listdir(法条库目录):
        if not 文件名.endswith('.txt') or 文件名 == 'missing_laws.txt':
            continue
        try:
            with open(os.path.join(法条库目录, 文件名), "r", encoding="utf-8") as f:
                全文表[文件名] = f.read()
        except OSError:
            continue        # 单部法读不动，不该把其余法条的校验一起带崩
    return 全文表


def _记录库外引用(法条库目录, 库外列表):
    """把"库里没这部法"的引用记进 missing_laws.txt —— 它是**补库清单**。

    ⚠️ 原来按整行去重，而写进去的行带日期前缀（`2026-06-14\\t《民法典》第667条`），
    比对用的却是**不带日期的裸引用** ⇒ 两边永远不相等 ⇒ 去重形同虚设。
    盘上那份日志里同一天的同一条重复出现，就是这条的证据。改成按引用本身去重。
    """
    if not 库外列表:
        return
    缺失日志 = os.path.join(法条库目录, "missing_laws.txt")
    try:
        已有 = set()
        if os.path.exists(缺失日志):
            with open(缺失日志, "r", encoding="utf-8") as f:
                for 行 in f:
                    已有.add(行.strip().split("\t")[-1].strip())
        新增 = [r for r in 库外列表 if r not in 已有]
        if 新增:
            with open(缺失日志, "a", encoding="utf-8") as f:
                for r in 新增:
                    f.write(f"{date.today()}\t{r}\n")
    except OSError:
        pass                # 记不上日志不影响本次校验的结论


def classify_law_citations(法条库目录, 案发日期, *分析列表):
    """把AI对法条的引用分成**三态**，并把"没能校验的"单独计数。

    返回：
      可验证      [{引用,法名,文件,条文,状态,施行日期,取代,版本警告}]
      疑似编造    [引用]  **库里有这部法、但没有这个条号** —— 只有这一类配指控编造
      库外        [引用]  库里没这部法。**不等于引用是假的**，只是本工具覆盖不到
      未识别      [引用]  提不出法名或条号（如"参照本法第七百九十三条"），无从校验
      无条号引用  [《某法》]  只写了法名没给条号，结构上无法校验
      已校验数 / 覆盖不足数 / 未校验数 / 案发日期已知

    ⚠️ 为什么是三态而不是两态：原来 `verify_law_citation_realness` 把
    "库里没这部法"和"库里有这部法但没有这一条"塞进同一个 `未找到` 列表，
    而它的两个消费者对**同一批数据**给了相反的判据 ——
    `score_analysis.compute_trust_score` 按"中性、覆盖不足"处理
    （它自己的注释就写着"法条不在库里≠错误"），
    `score_analysis.generate_risk_list` 却标成 danger +
    "AI引用了法条库中不存在的条文，请人工核实该法条是否真实存在"。
    实测会进那条 danger 的里面有《电子签名法》第3条、《合伙企业法》第三十三条
    —— **都是真实存在的法**。库只有 11 部法，而实务分析必然引司法解释和下位法，
    于是 danger 常亮 ⇒ 用户学会忽略红色告警，而红色告警是这套机制唯一有用的输出。
    ⇒ 判据在这里算一次，两个消费者都读这一份，别各判各的。
    """
    结果 = {"可验证": [], "疑似编造": [], "库外": [], "未识别": [], "无条号引用": [],
            "已校验数": 0, "覆盖不足数": 0, "未校验数": 0,
            "案发日期已知": bool(案发日期)}
    if not os.path.isdir(法条库目录):
        return 结果

    合并 = " ".join(分析列表)
    全文表 = _读取法条库(法条库目录)

    for 引用 in _提取法条引用(合并):
        法名 = _解析法名(引用)
        条文号匹配 = re.search(r'第\s*([一二三四五六七八九十百千\d]+)\s*条', 引用)
        if not 法名 or not 条文号匹配:
            结果["未识别"].append(引用)
            continue
        if _是相对指代(引用, 法名):
            结果["未识别"].append(引用)     # "参照本法…" —— 不是库里缺这部法，别写进补库清单
            continue
        候选 = {n: t for n, t in 全文表.items() if 法名 in n}
        if not 候选:
            结果["库外"].append(引用)
            continue
        条标 = f"第{_文章号转数字(条文号匹配.group(1))}条"
        命中文件, 位置 = "", -1
        for 文件名, 全文 in 候选.items():
            位置 = 全文.find(条标)
            if 位置 >= 0:
                命中文件 = 文件名
                break
        if 位置 < 0:
            结果["疑似编造"].append(引用)
            continue
        全文 = 候选[命中文件]
        元数据 = _解析法条元数据(os.path.join(法条库目录, 命中文件))
        条目 = {
            "引用": 引用,
            "法名": 法名,
            "文件": 命中文件,
            "条文": 全文[max(0, 位置):位置 + 300].strip() + "……",
            "状态": 元数据.get("状态", "未知"),
            "施行日期": 元数据.get("施行日期", ""),
            "取代": 元数据.get("取代", ""),
            # ⚠️ `版本警告` 这个键原来**没有任何地方写**，而两个消费者都在读它
            # —— 于是"已废止/已修订/案发早于施行"这套判据从未生效过。在这儿接上。
            "版本警告": verify_law_version(案发日期, 元数据) or "",
        }
        结果["可验证"].append(条目)

    # 只提法名、没给条号的援引：不进三态，单独计数（它们一次都没被校验过）
    for 匹配 in re.finditer(法名正则, 合并):
        if 条号后缀.match(合并[匹配.end():匹配.end() + 20]):
            continue
        结果["无条号引用"].append(匹配.group())
    结果["无条号引用"] = sorted(set(结果["无条号引用"]))

    结果["已校验数"] = len(结果["可验证"]) + len(结果["疑似编造"])
    结果["覆盖不足数"] = len(结果["库外"])
    结果["未校验数"] = len(结果["无条号引用"]) + len(结果["未识别"])
    _记录库外引用(法条库目录, 结果["库外"])
    return 结果


# ═══════════════════════════════════════════════════════════
# Skill 4: 法条版本校验
# ═══════════════════════════════════════════════════════════

def verify_law_version(案发日期, 法条条目):
    """比对案发时间与法条版本，返回警告文字或None"""
    施行日期 = 法条条目.get("施行日期", "")
    状态 = 法条条目.get("状态", "")
    if not 施行日期:
        return None
    try:
        案发 = date.fromisoformat(案发日期)
        施行 = date.fromisoformat(施行日期)
        if 案发 < 施行:
            return f"⚠️ 案发时间({案发日期})早于本法条施行日期({施行日期})，可能适用旧法"
    except Exception:
        pass
    if 状态 == "已废止":
        return "⚠️ 本法条已废止，请核实是否仍可援引"
    if 状态 == "已修订":
        return "⚠️ 本法条已修订，请核实案发时适用的版本"
    return None


def _解析法名(引用):
    """从法条引用中提取法名，如'《民法典》第1165条'→'民法典'"""
    # 优先取《》内的完整法名
    法名匹配 = re.search(r'《([^》]+)》', 引用)
    if 法名匹配:
        全名 = 法名匹配.group(1).strip()
    else:
        # 回退：无书名号时匹配"XX法"模式
        法名匹配 = re.search(r'([^\s，。；、]{2,20}[法典])', 引用)
        全名 = 法名匹配.group(1) if 法名匹配 else None
    # 全称归一为简称，匹配文件名
    if 全名:
        for 简称 in ['民法典', '刑法', '宪法', '行政法', '民事诉讼法', '刑事诉讼法']:
            if 简称 in 全名:
                return 简称
        return 全名
    return None
