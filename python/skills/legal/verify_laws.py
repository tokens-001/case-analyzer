def count_law_citations(*分析列表):
    """统计AI分析中引用了多少条法律条文"""
    合并 = " ".join(分析列表)
    法条集合 = sorted(set(_提取法条引用(合并)))
    if 法条集合:
        列出 = 法条集合[:5]
        余 = len(法条集合) - len(列出)
        return f"引用法条 {len(法条集合)} 条：" + "、".join(列出) + (f"…（另有 {余} 条未列出）" if 余 else "")
    return "未引用法律条文"


