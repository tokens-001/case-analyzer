# Skill 2: 法条三态校验 —— 本模块唯一的判据出口
# ═══════════════════════════════════════════════════════════

def _读取法条库(法条库目录):
    """把库里的法条文本一次读进内存 {文件名: 全文}。

    原来两条查库的路径各自反复读盘：`verify_law_citation_realness` 在
    "引用 × 候选文件"的双层循环里对同一份文件 `open().read()` 好几遍，
    `search_law_database` 又自己走一遍。合并成一次读盘、一次判定。
    """
    全文表 = {}
    for 文件名 in os.listdir(法条库目录):
        if not 文件名.endswith('.txt') or 文件名 == 'missing_laws.txt':
            continue
        try:
            with open(os.path.join(法条库目录, 文件名), "r", encoding="utf-8") as f:
                全文表[文件名] = f.read()
        except OSError:
            continue        # 单部法读不动，不该把其余法条的校验一起带崩
    return 全文表


def _记录库外引用(法条库目录, 库外列表):
    """把"库里没这部法"的引用记进 missing_laws.txt —— 它是**补库清单**。

    ⚠️ 原来按整行去重，而写进去的行带日期前缀（`2026-06-14\\t《民法典》第667条`），
    比对用的却是**不带日期的裸引用** ⇒ 两边永远不相等 ⇒ 去重形同虚设。
    盘上那份日志里同一天的同一条重复出现，就是这条的证据。改成按引用本身去重。
    """
    if not 库外列表:
        return
    缺失日志 = os.path.join(法条库目录, "missing_laws.txt")
    try:
        已有 = set()
        if os.path.exists(缺失日志):
            with open(缺失日志, "r", encoding="utf-8") as f:
                for 行 in f:
                    已有.add(行.strip().split("\t")[-1].strip())
        新增 = [r for r in 库外列表 if r not in 已有]
        if 新增:
            with open(缺失日志, "a", encoding="utf-8") as f:
                for r in 新增:
                    f.write(f"{date.today()}\t{r}\n")
    except OSError:
        pass                # 记不上日志不影响本次校验的结论


# ═══════════════════════════════════════════════════════════
# 案发时间归一化
# ═══════════════════════════════════════════════════════════

日期段 = re.compile(r'^\d{4}(?:-\d{1,2}){0,2}$')

def 规范案发日期(原始值):
    """把人填的案发时间收成一个能拿来比的日子；收不下返回 None。

    接受 2023-04-05 / 2023/4/5 / 2023.4.5 / 2023年4月5日，也接受只填到
    月（2023-04、2019年5月）或只填年（2023、2023年）—— 判决书里常常只有
    "2019年5月"这种精度，逼用户凑一个假日子，比让用户少填更糟。缺的部分补
    1 号：往早取，这样"案发早于本法条施行"不会因为补到月末而漏报。

    ⚠️ 为什么返回 None 而不是原样回传：调用方必须能分清**没填**和**填了但读不懂**。
    两者对判据的影响一样（时效未校验），对用户不一样 —— 把"2019年左右"悄悄当成
    没填，用户会以为绿灯背后跑过时效校验，而它一次都没跑过。
    """
    if not isinstance(原始值, str):
        return None
    写 = 原始值.strip().replace("年", "-").replace("月", "-").replace("/", "-").replace(".", "-")
    写 = re.sub(r"日$", "", 写)
    写 = re.sub(r"-+", "-", 写).strip("-")        # "2023年"→"2023"，"2023-04-"→"2023-04"
    if not 日期段.match(写):
        return None
    段 = [int(x) for x in 写.split("-")]
    段 += [1] * (3 - len(段))
    try:
        return date(*段).isoformat()
    except ValueError:
        return None         # 形状对但不是日子（13月、2月30日）


def classify_law_citations(法条库目录, 案发日期, *分析列表):
    """把AI对法条的引用分成**三态**，并把"没能校验的"单独计数。

    返回：
      可验证      [{引用,法名,文件,条文,状态,施行日期,取代,版本警告}]
      疑似编造    [引用]  **库里有这部法、但没有这个条号** —— 只有这一类配指控编造
      库外        [引用]  库里没这部法。**不等于引用是假的**，只是本工具覆盖不到
      未识别      [引用]  提不出法名或条号（如"参照本法第七百九十三条"），无从校验
      无条号引用  [《某法》]  只写了法名没给条号，结构上无法校验
      已校验数 / 覆盖不足数 / 未校验数
      案发日期已知   填了**且能读懂**才为 True
      案发日期原文 / 案发日期无法解析  填了但读不懂时，这两个键供调用方出声

    ⚠️ 为什么是三态而不是两态：原来 `verify_law_citation_realness` 把
    "库里没这部法"和"库里有这部法但没有这一条"塞进同一个 `未找到` 列表，
    而它的两个消费者对**同一批数据**给了相反的判据 ——
    `score_analysis.compute_trust_score` 按"中性、覆盖不足"处理
    （它自己的注释就写着"法条不在库里≠错误"），
    `score_analysis.generate_risk_list` 却标成 danger +
    "AI引用了法条库中不存在的条文，请人工核实该法条是否真实存在"。
    实测会进那条 danger 的里面有《电子签名法》第3条、《合伙企业法》第三十三条
    —— **都是真实存在的法**。库只有 11 部法，而实务分析必然引司法解释和下位法，
    于是 danger 常亮 ⇒ 用户学会忽略红色告警，而红色告警是这套机制唯一有用的输出。
    ⇒ 判据在这里算一次，两个消费者都读这一份，别各判各的。
    """
    案发 = 规范案发日期(案发日期)
    原始案发 = (案发日期 or "").strip()[:40] if isinstance(案发日期, str) else ""
    结果 = {"可验证": [], "疑似编造": [], "库外": [], "未识别": [], "无条号引用": [],
            "已校验数": 0, "覆盖不足数": 0, "未校验数": 0,
            "案发日期已知": 案发 is not None,
            "案发日期原文": 原始案发,
            "案发日期无法解析": bool(原始案发) and 案发 is None}
    if not os.path.isdir(法条库目录):
        return 结果

    合并 = " ".join(分析列表)
    全文表 = _读取法条库(法条库目录)

    for 引用 in _提取法条引用(合并):
        法名 = _解析法名(引用)
        条文号匹配 = re.search(条号带变体, 引用)
        if not 法名 or not 条文号匹配:
            结果["未识别"].append(引用)
            continue
        if _是相对指代(引用, 法名):
            结果["未识别"].append(引用)     # "参照本法…" —— 不是库里缺这部法，别写进补库清单
            continue
        候选 = {n: t for n, t in 全文表.items() if 法名 in n}
        if not 候选:
            结果["库外"].append(引用)
            continue
        基条标 = f"第{_文章号转数字(条文号匹配.group(1))}条"
        变体 = 条文号匹配.group(2) or ""
        # ⚠️ "之一"这个后缀原来整个被丢掉：《刑法》第133条之一（危险驾驶罪）会去匹配
        # 第133条（交通肇事罪），并且**返回同一段"原文"** —— 假绿灯。
        条标 = 基条标 + (f"之{变体}" if 变体 else "")
        命中文件, 位置 = "", -1
        基条在库 = False
        for 文件名, 全文 in 候选.items():
            位置 = 全文.find(条标)
            if 位置 >= 0:
                命中文件 = 文件名
                break
            if 变体 and 全文.find(基条标) >= 0:
                基条在库 = True
        if 位置 < 0:
            if 基条在库:
                # 库里有"第133条"却没有"第133条之一" —— 这是**库不全**，不是有人编造。
                # 判成疑似编造就是对着真实法条亮红牌，那正是这套机制最不能犯的错。
                结果["未识别"].append(引用)
                continue
            结果["疑似编造"].append(引用)
            continue
        全文 = 候选[命中文件]
        元数据 = _解析法条元数据(os.path.join(法条库目录, 命中文件))
        条目 = {
            "引用": 引用,
            "法名": 法名,
            "文件": 命中文件,
            "条文": 全文[max(0, 位置):位置 + 300].strip() + "……",
            "状态": 元数据.get("状态", "未知"),
            "施行日期": 元数据.get("施行日期", ""),
            "取代": 元数据.get("取代", ""),
            # ⚠️ `版本警告` 这个键原来**没有任何地方写**，而两个消费者都在读它
            # —— 于是"已废止/已修订/案发早于施行"这套判据从未生效过。在这儿接上。
            # 传的是**归一化之后**的日期：用户填"2019年5月"也该能比，填"2019年左右"
            # 则传空串下去（时效比不了就是比不了，别让一个读不懂的字符串冒充比过了）。
            "版本警告": verify_law_version(案发 or "", 元数据) or "",
        }
        结果["可验证"].append(条目)

    # 只提法名、没给条号的援引：不进三态，单独计数（它们一次都没被校验过）
    for 匹配 in re.finditer(法名正则, 合并):
        if 条号后缀.match(合并[匹配.end():匹配.end() + 20]):
            continue
        结果["无条号引用"].append(匹配.group())
    结果["无条号引用"] = sorted(set(结果["无条号引用"]))

    结果["已校验数"] = len(结果["可验证"]) + len(结果["疑似编造"])
    结果["覆盖不足数"] = len(结果["库外"])
    结果["未校验数"] = len(结果["无条号引用"]) + len(结果["未识别"])
    _记录库外引用(法条库目录, 结果["库外"])
    return 结果


# ═══════════════════════════════════════════════════════════
# Skill 4: 法条版本校验
# ═══════════════════════════════════════════════════════════

def verify_law_version(案发日期, 法条条目):
    """比对案发时间与法条版本，返回警告文字或None"""
    施行日期 = 法条条目.get("施行日期", "")
    状态 = 法条条目.get("状态", "")
    # 状态告警先看 —— 它不依赖施行日期。原来 `if not 施行日期: return None` 排在最前，
    # 于是一部没写施行日期的库文件哪怕标着 状态: 已废止 也会静默返回 None：
    # 缺一份元数据，把另一条跟它无关的判据一起吞了。
    if 状态 == "已废止":
        return "⚠️ 本法条已废止，请核实是否仍可援引"
    if 状态 == "已修订":
        return "⚠️ 本法条已修订，请核实案发时适用的版本"
    案发 = 规范案发日期(案发日期)
    if not (施行日期 and 案发):
        return None
    try:
        if date.fromisoformat(案发) < date.fromisoformat(施行日期):
            return f"⚠️ 案发时间({案发})早于本法条施行日期({施行日期})，可能适用旧法"
    except ValueError:
        pass                # 库里施行日期本身写坏了 —— 是数据问题，本次不下判断
    return None


def _解析法名(引用):
    """从法条引用中提取法名，如'《民法典》第1165条'→'民法典'"""
    # 优先取《》内的完整法名
    法名匹配 = re.search(r'《([^》]+)》', 引用)
    if 法名匹配:
        全名 = 法名匹配.group(1).strip()
    else:
        # 回退：无书名号时匹配"XX法"模式。⚠️ 这个字符类必须把括号、星号、引号都排除掉 ——
        # 原来只排了空白和读点，于是正文里的"*公平责任**（民法典第1186条"被整段当成法名，
        # 靠上面那张写死的简称白名单"子串命中"才救回来。白名单一拿掉就露馅：
        # 该修的是这条正则，不是再补一个简称。
        法名匹配 = 法名回退.search(引用)
        全名 = 法名匹配.group(1) if 法名匹配 else None
    # 全称归一为简称，匹配文件名。
    # ⚠️ 原来这里是一张写死的白名单 ['民法典','刑法','宪法','行政法','民事诉讼法','刑事诉讼法']，
    #   于是《中华人民共和国公司法》《中华人民共和国著作权法》这类**判决书里的标准写法**
    #   带着前缀去比对文件名 ⇒ 对不上 ⇒ 判成"库里没这部法"。
    #   库里明明有。前缀是固定的，剥掉它就行，不需要名单 —— 名单只会漏。
    if 全名:
        简称 = 全名.replace("中华人民共和国", "").strip()
        return 简称 or 全名
    return None
