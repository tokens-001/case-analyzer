"""
技能集：法条校验

包含：
- count_law_citations: 从分析文本中统计法条引用
- classify_law_citations: **三态**校验（可验证 / 疑似编造 / 库外）+ 两类"没能校验"
- verify_law_version: 比对案发日期与法条施行日期、检查废止/修订状态

全部本地运行，不调API。法条库路径由调用方传入。

⚠️ `classify_law_citations` 是本模块**唯一**的法条校验判据出口。
   原来这里有两个函数各自查库（`search_law_database` 和
   `verify_law_citation_realness`），而它们的结果被两个消费者读，
   两边对**同一批数据**给了相反的判据（详见那个函数的 docstring）。
   再加一个"查一遍库"的函数等于把这个分歧再复制一份。
"""

import os
import re
from datetime import date

def _文章号转数字(文章号):
    """将中文数字条文号转为阿拉伯数字，如 '六百六十七' → 667"""
    if 文章号.isdigit():
        return int(文章号)
    cn_nums = {'一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,
               '零':0,'十':10,'百':100,'千':1000}
    s = 文章号.replace('零', '').replace('〇', '')
    result, current = 0, 0
    for ch in s:
        if ch == '千': result += (current or 1) * 1000; current = 0
        elif ch == '百': result += (current or 1) * 100; current = 0
        elif ch == '十': result += (current or 1) * 10; current = 0
        else: current = cn_nums.get(ch, 0)
    return result + current


