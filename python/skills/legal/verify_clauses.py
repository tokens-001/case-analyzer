"""合同风险结论的**条款锚点校验** —— 本地运行，不调 API。

为什么要有它：合同场景最常出的幻觉不是编法条，是**编一份不存在的约定**
（"第八条约定违约金为合同总额30%"，而合同里根本没这条）。这种错只有拿
结论引用的原文去跟**用户自己上传的那份文件**对得上才算被检验过 ——
这条判据和 `trace_citations` 的段号越界一样，属于"不可能假指控"的那类：
要么对得上，要么就是对不上，不涉及模型自评。

判据与 `verify_laws.classify_law_citations` 同构（三态 + 两类未校验），
两边共享的规矩：**没校验到的东西必须自己报出来**，不许算进"通过"。

模型侧要求的写法（写在技能提示词里，两边一起改，别只改一头）：
    【第N条】「原文摘录……」风险：…… 建议：……
"""

# 提示词里的格式要求与检查它的判据放同一个文件：改一侧必然撞见另一侧。
# 分在两个文件里漂移，就是"提示词没写 fix_route、下游却拿它路由"那一类的成因。
引用格式要求 = (
    '每条结论单独一行，行首写成：- 【第N条】「从合同该条原文逐字摘录的短句」 风险：… 建议：…\n'
    '摘录必须能在该条原文里逐字找到（中间可用……省略），做不到就不要写这条结论。\n'
    '只给条号不给摘录、或摘了原文里不存在的话，会被本地校验判为「未校验」或「疑似编造」。'
)
import re

锚点 = re.compile(r'【第\s*([0-9〇一二三四五六七八九十百千零]{1,8})\s*条】'
                  r'\s*(?:[「『]([^」』]{2,200})[」』])?')
列表项 = re.compile(r'^\s*(?:[（(]?\d{1,3}[）).、]|[-•●])', re.M)
# 归一化要掉的：空白 + 中英文标点/引号差异（摘录常因全半角、句读、引号不一致而对不上）。
# 字符集用 re.escape 现拼，不手写字符类 —— 手写在类里放 ASCII 引号会把字符串本身截断。
标点 = (' \t\n\r　，。、；：（）()[]【】—-<>《》“”‘’「」『』,.;:!?&*' + chr(34) + chr(39))
去噪 = re.compile('[' + re.escape(标点) + ']+')


def _归一(文字):
    return 去噪.sub('', 文字 or '')


def _摘录对得上(摘录, 条正文):
    """摘录按省略号切段，每段（≥6 字）都必须能在该条正文里找到。

    整体 substring 会因模型中途用"……"省略而误判；只比首段又会放过改写了后半句的
    情况。切段逐条比是这两者之间最小的可靠折中。
    """
    干 = _归一(摘录)
    if not 干:
        return False
    片 = [ _归一(p) for p in re.split(r'…{1,2}|\.{3}', 摘录) if len(_归一(p)) >= 6 ]
    if not 片:
        return 干 in _归一(条正文)
    return all(p in _归一(条正文) for p in 片)


def verify_clause_anchors(条款表, *分析列表):
    """按三态给合同分析里的每条引用下结论。

    条款表：`parse_doc.解析()` 返回的 {'条号': 正文}，两边同源，不会漂。
    返回：
      可验证    [{引用条号, 摘录, 命中}]        条号存在 + 摘录对得上
      疑似编造  [{引用条号, 摘录, 原因}]        条号不存在 / 摘录在该条正文里找不到
      无摘录    [{引用条号}]                    只给条号不给原文，无法证实它读了那条
      无锚点条目 [...]                          有风险条目却没挂任何条号
      已校验数 / 未校验数
    """
    结果 = {'可验证': [], '疑似编造': [], '无摘录': [], '无锚点条目': [],
            '已校验数': 0, '未校验数': 0}
    if not 条款表:
        # 没有条款表 = 这份文本没解析出条号结构，一次校验都没发生 ——
        # 必须说成"未校验"，不能报 0/0 让人以为"没有风险条目，所以全过"
        合并 = "\n".join(x or '' for x in 分析列表)
        结果['未校验数'] = len(列表项.findall(合并))
        结果['无锚点条目'] = ['（无条款表，全部条目未校验）'] if 结果['未校验数'] else []
        return 结果

    合并 = "\n".join(x or '' for x in 分析列表)
    for 匹配 in 锚点.finditer(合并):
        号, 摘录 = 匹配.group(1), (匹配.group(2) or '').strip()
        if 号 not in 条款表:
            结果['疑似编造'].append({'引用条号': 号, '摘录': 摘录,
                                     '原因': f"合同里没有第{号}条（实际条号：{'、'.join(list(条款表)[:12])}）"})
            continue
        if not 摘录:
            结果['无摘录'].append({'引用条号': 号})
            continue
        if _摘录对得上(摘录, 条款表[号]):
            结果['可验证'].append({'引用条号': 号, '摘录': 摘录, '命中': True})
        else:
            结果['疑似编造'].append({'引用条号': 号, '摘录': 摘录,
                                     '原因': f"第{号}条里没有这句话，该条实际是：{条款表[号][:80]}"})

    # 挂了条号的行算"有锚点"；剩下的编号列表项才是无锚点条目
    无锚点 = []
    for 行 in 合并.split('\n'):
        if 列表项.match(行) and 锚点.search(行) is None and '【' not in 行:
            无锚点.append(行.strip()[:70])
    结果['无锚点条目'] = 无锚点
    结果['已校验数'] = len(结果['可验证'])
    结果['未校验数'] = len(结果['无摘录']) + len(无锚点)
    return 结果
