"""合同风险结论的**条款锚点校验** —— 本地运行，不调 API。

为什么要有它：合同场景最常出的幻觉不是编法条，是**编一份不存在的约定**
（"第八条约定违约金为合同总额30%"，而合同里根本没这条）。这种错只有拿
结论引用的原文去跟**用户自己上传的那份文件**对得上才算被检验过 ——
这条判据和 `trace_citations` 的段号越界一样，属于"不可能假指控"的那类：
要么对得上，要么就是对不上，不涉及模型自评。

判据与 `verify_laws.classify_law_citations` 同构（三态 + 两类未校验），
两边共享的规矩：**没校验到的东西必须自己报出来**，不许算进"通过"。

模型侧要求的写法（写在技能提示词里，两边一起改，别只改一头）：
    【第N条】「原文摘录……」风险：…… 建议：……
"""

# 提示词里的格式要求与检查它的判据放同一个文件：改一侧必然撞见另一侧。
# 分在两个文件里漂移，就是"提示词没写 fix_route、下游却拿它路由"那一类的成因。
引用格式要求 = (
    '每条结论单独一行，行首写成：- 【第N条】「从合同该条原文逐字摘录的短句」 风险：… 建议：…\n'
    '指到某一条里的第几款时，写成【第N条第M款】，摘录仍从该款原文里逐字取。\n'
    '摘录必须能在该条（或该款）原文里逐字找到（中间可用……省略），做不到就不要写这条结论。\n'
    '只给条号不给摘录、或摘了原文里不存在的话，会被本地校验判为「未校验」或「疑似编造」。'
)
import re

from .verify_laws import _文章号转数字

# ⚠️ 原来这个正则要求 `条` 后面紧跟 `】`，于是模型真实写出来的【第二条第3款】整体匹配不上；
#   而下面"无锚点条目"那道兜底又用 `'【' not in 行` 把这种行排除了 —— 两边都不管，
#   这 19 条引用就**静默消失**：不判可验证、不判疑似编造、也不计进未校验。
#   实测一份真合同：48 个锚点里 19 个是带款后缀的，全从这个缝里漏掉。
#   现在款后缀进正则，并且另加一条兜底：像引用却解析不了的，一律计入未校验。
锚点 = re.compile(r'【第\s*([0-9〇一二三四五六七八九十百千零]{1,8})\s*条'
                  r'(?:\s*第\s*([0-9〇一二三四五六七八九十百千]{1,4})\s*款)?'
                  r'】\s*(?:[「『]([^」』]{2,200})[」』])?')
# 长得像"条号引用"却被上面解析不了的方括号 —— 宁可计成未校验，也不许它悄悄过去
引用形状 = re.compile(r'【[^】]*第[^】]*条[^】]*】')
列表项 = re.compile(r'^\s*(?:[（(]?\d{1,3}[）).、]|[-•●])', re.M)
# 款号：合同里通常写成"1、""2、"。认不出这种编号的合同（用（一）或不分款）不去指控款号。
款号行 = re.compile(r'^\s*(\d{1,3})\s*[、.．]')
# 归一化要掉的：空白 + 中英文标点/引号差异（摘录常因全半角、句读、引号不一致而对不上）。
# 字符集用 re.escape 现拼，不手写字符类 —— 手写在类里放 ASCII 引号会把字符串本身截断。
标点 = (' \t\n\r　，。、；：（）()[]【】—-<>《》“”‘’「」『』,.;:!?&*' + chr(34) + chr(39))
去噪 = re.compile('[' + re.escape(标点) + ']+')


def _归一(文字):
    return 去噪.sub('', 文字 or '')


def _摘录对得上(摘录, 条正文):
    """摘录按省略号切段，每段（≥6 字）都必须能在该条正文里找到。

    整体 substring 会因模型中途用"……"省略而误判；只比首段又会放过改写了后半句的
    情况。切段逐条比是这两者之间最小的可靠折中。
    """
    干 = _归一(摘录)
    if not 干:
        return False
    片 = [ _归一(p) for p in re.split(r'…{1,2}|\.{3}', 摘录) if len(_归一(p)) >= 6 ]
    if not 片:
        return 干 in _归一(条正文)
    return all(p in _归一(条正文) for p in 片)


def _拆款(正文):
    """按"1、2、3、"这种显式编号把一条拆成款。拆不出来说明这份合同不这么编号 → 调用方别指控款号。"""
    行们 = (正文 or '').split('\n')
    起点 = [i for i, 行 in enumerate(行们) if 款号行.match(行)]
    if not 起点:
        return []
    return ['\n'.join(行们[i:(起点[起点.index(i)+1] if 起点.index(i)+1 < len(起点) else len(行们))])
            for i in 起点]


def verify_clause_anchors(条款表, *分析列表):
    """按三态给合同分析里的每条引用下结论。

    条款表：`parse_doc.解析()` 返回的 {'条号': 正文}，两边同源，不会漂。
    返回：
      可验证    [{引用条号, 摘录, 命中}]        条号存在 + 摘录对得上
      疑似编造  [{引用条号, 摘录, 原因}]        条号不存在 / 款号超出该条款数 / 摘录找不到
      无摘录    [{引用条号}]                    只给条号不给原文，无法证实它读了那条
      无锚点条目 [...]                          有风险条目却没挂任何条号
      锚点无法解析 [...]                        长得像条号引用、正则却吃不下（新格式？写错了？）
      已校验数 / 未校验数
    """
    结果 = {'可验证': [], '疑似编造': [], '无摘录': [], '无锚点条目': [], '锚点无法解析': [],
            '已校验数': 0, '未校验数': 0}
    if not 条款表:
        # 没有条款表 = 这份文本没解析出条号结构，一次校验都没发生 ——
        # 必须说成"未校验"，不能报 0/0 让人以为"没有风险条目，所以全过"
        合并 = "\n".join(x or '' for x in 分析列表)
        结果['未校验数'] = len(列表项.findall(合并))
        结果['无锚点条目'] = ['（无条款表，全部条目未校验）'] if 结果['未校验数'] else []
        return 结果

    合并 = "\n".join(x or '' for x in 分析列表)
    for 匹配 in 锚点.finditer(合并):
        号, 款写, 摘录 = 匹配.group(1), 匹配.group(2), (匹配.group(3) or '').strip()
        if 号 not in 条款表:
            结果['疑似编造'].append({'引用条号': 号, '摘录': 摘录,
                                     '原因': f"合同里没有第{号}条（实际条号：{'、'.join(list(条款表)[:12])}）"})
            continue
        正文 = 条款表[号]
        定位, 位置说明 = 正文, f"第{号}条"
        if 款写:
            款表 = _拆款(正文)
            第几 = _文章号转数字(款写)
            if 款表 and 第几 > len(款表):
                # 这一类可以指控：款号是合同里明写的编号，不是解释空间
                结果['疑似编造'].append({'引用条号': 号, '摘录': 摘录,
                                         '原因': f"第{号}条只有 {len(款表)} 款，没有第{第几}款"})
                continue
            if 款表:
                定位 = 款表[第几 - 1]
                位置说明 = f"第{号}条第{第几}款"
            # 拆不出款号（这份合同不写"1、2、"）→ 退回整条比对，不指控款号
        if not 摘录:
            结果['无摘录'].append({'引用条号': 号})
            continue
        if _摘录对得上(摘录, 定位):
            结果['可验证'].append({'引用条号': 号, '摘录': 摘录, '命中': True})
        else:
            结果['疑似编造'].append({'引用条号': 号, '摘录': 摘录,
                                     '原因': f"{位置说明}里没有这句话，该处实际是：{定位[:80]}"})

    # 挂了条号的行算"有锚点"；剩下的编号列表项才是无锚点条目
    无锚点 = []
    for 行 in 合并.split('\n'):
        if 列表项.match(行) and 锚点.search(行) is None and '【' not in 行:
            无锚点.append(行.strip()[:70])
    结果['无锚点条目'] = 无锚点
    # 兜底：像条号引用、却没被上面任何一条规则接住的，显式计成未校验。
    # 带款后缀那批当初就是掉在"正则不匹配 + 无锚点又排除有【的行"两道规则的缝里，
    # 一声不吭 —— 这条兜底保证以后再加新写法也不会再出现"看不见就等于过了"。
    # ⚠️ 判"接住没有"要拿**方括号本身**去 fullmatch：`匹配.group()` 连摘录一起吃进去了，
    #   拿它跟裸括号比会把每一条都判成"没接住"（实测误报 23 条）。
    结果['锚点无法解析'] = [括号 for 括号 in dict.fromkeys(引用形状.findall(合并))
                     if not 锚点.fullmatch(括号)]
    结果['已校验数'] = len(结果['可验证'])
    结果['未校验数'] = len(结果['无摘录']) + len(无锚点) + len(结果['锚点无法解析'])
    return 结果
