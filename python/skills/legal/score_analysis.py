"""
技能集：分析质量评估

包含3个技能：
- validate_analysis_quality: 基础质量验证（字数、法条引用）
- generate_risk_list: 三级风险汇总（验证+法条版本+溯源越界+法条真实性）
- compute_trust_score: 综合可信度评分（0-100分+等级+明细来源）

全部本地运行，不调API。
"""


# ═══════════════════════════════════════════════════════════
# Skill 1: 分析质量验证
# ═══════════════════════════════════════════════════════════

def validate_analysis_quality(分析1, 分析2, 分析3, 分析4, 总结, 法条统计函数):
    """基础质量检查：字数+法条引用"""
    问题列表 = []
    if len(分析1) < 20: 问题列表.append("核心争议字数过少，可能API异常")
    if len(分析2) < 20: 问题列表.append("推理链路字数过少，可能API异常")
    if len(分析3) < 20: 问题列表.append("未回答问题字数过少，可能API异常")
    if len(分析4) < 20: 问题列表.append("可平移性字数过少，可能API异常")
    if len(总结) < 50: 问题列表.append("总结字数过少")

    法条结果 = 法条统计函数(分析1, 分析2, 分析3, 分析4)
    if 法条结果 == "未引用法律条文":
        问题列表.append("四段分析均未引用法律条文")

    return {"通过": len(问题列表) == 0, "问题": 问题列表, "法条统计": 法条结果}


# ═══════════════════════════════════════════════════════════
# Skill 2: 风险列表生成
# ═══════════════════════════════════════════════════════════

def generate_risk_list(验证, 法条校验, 溯源):
    """把校验结果汇成风险列表。等级三档：danger（要停下来核实）/ warning（结论有边界）/ note（说明）。

    ⚠️ **只有"不可能假指控"的判据才配 danger**：
      · 库里有这部法、却查不到这一条 → 疑似编造
      · 法条已废止/已修订/案发早于施行 → 时效问题
      · AI 标注的原文段号越界 → 结构上必然是编的
    而"库里没这部法""只写了法名没给条号"这些**是工具的覆盖边界，不是AI的错误**，
    原来全被并进 danger 那一条文案（"AI引用了法条库中不存在的条文"），
    而实测被这样指控的《电子签名法》第3条、《合伙企业法》第三十三条都是真实存在的法。
    danger 常亮会让人学会忽略它 —— 那是这套机制唯一有用的输出。判据来自
    `verify_laws.classify_law_citations`，本函数不再自行判断真伪。
    """
    校验 = 法条校验 or {}
    风险 = []

    # ── danger：可指控的三类 ──
    for 引用 in 校验.get("疑似编造", []):
        风险.append({"等级": "danger", "内容": f"法条库里有这部法，却查不到这个条号：{引用} —— 疑似编造，请人工核实"})
    for 条目 in 校验.get("可验证", []):
        if 条目.get("版本警告"):
            风险.append({"等级": "danger", "内容": 条目["版本警告"]})
    if 溯源 and 溯源.get("items"):
        for item in 溯源["items"]:
            if not item.get("有效"):
                风险.append({"等级": "danger", "内容": f"AI编造引用：原文第{item['段号']}段不存在（共{溯源['总段落数']}段）"})

    # ── warning：本次结论的覆盖边界 ──
    无条号 = 校验.get("无条号引用", [])
    if 无条号:
        风险.append({"等级": "warning", "内容":
                     f"有 {len(无条号)} 处援引只写了法名、没给条号（{'、'.join(无条号[:3])}{'等' if len(无条号) > 3 else ''}）"
                     f"—— 这类引用结构上无法校验，本页的『已校验』不含它们"})
    未识别 = 校验.get("未识别", [])
    if 未识别:
        风险.append({"等级": "warning", "内容":
                     f"另有 {len(未识别)} 处引用无法定位到具体法律（如『{'、'.join(未识别[:2])}』），本次未校验"})
    if not 校验.get("案发日期已知"):
        风险.append({"等级": "warning", "内容": "未提供案发日期 —— 案发时该条是否已施行、是否已被修订，本次未做校验"})
    for 问题 in 验证.get("问题", []):
        风险.append({"等级": "warning", "内容": 问题})

    # ── note：库覆盖不足，不等于引用有误 ──
    库外 = 校验.get("库外", [])
    if 库外:
        风险.append({"等级": "note", "内容":
                     f"{len(库外)} 处援引的法律不在本工具的法条库内（{('、'.join(库外[:3]))}{'等' if len(库外) > 3 else ''}）"
                     f"—— 属覆盖不足，不代表引用有误；补库清单见 data/laws/missing_laws.txt"})
    return 风险


# ═══════════════════════════════════════════════════════════
# Skill 3: 可信度评分
# ═══════════════════════════════════════════════════════════

def compute_trust_score(验证, 法条校验, 溯源):
    """综合可信度等级（高/中/低）+ 评分明细。

    ⚠️ 定级规则改了一条：**"高"必须有真证据**。
    原来那句是 `if 危险信号 == 0 and 正面信号 >= 1: 等级 = "高"`，
    而"正面信号"里有一项来自 `validate_analysis_quality` 的通过 —— 它只查每段字数 ≥20。
    于是一份零可验证依据的分析（引用全在库外、案情模式没有溯源、四段字数都够）
    会拿到"高 = 可信"。字数达标是格式检查，不是内容证据，不能再抬等级。

    现在：
      低  有任何危险信号（疑似编造 / 时效问题 / 溯源段号越界）
      高  至少一条引用在库内查到原文（或原文溯源全部验证），
          且没有任何未校验项、没有库外引用、格式检查通过
      中  其余全部 —— 包括"其实什么都没校验到"这一种
    """
    校验 = 法条校验 or {}
    信号 = []
    危险信号 = 0

    可验证 = 校验.get("可验证", [])
    疑似编造 = 校验.get("疑似编造", [])
    无条号数 = len(校验.get("无条号引用", []))
    未识别数 = len(校验.get("未识别", []))
    案发未知 = not 校验.get("案发日期已知")
    覆盖不足数 = 校验.get("覆盖不足数", 0)
    # 未校验数**只读不算**：同一个量在两个消费者里各算一遍，正是本次在修的那个错
    未校验数 = 校验.get("未校验数", 无条号数 + 未识别数)

    if 可验证:
        信号.append({"来源": f"法条可验证({len(可验证)}条)", "方向": "正面"})
        有效数 = sum(1 for e in 可验证 if e.get("状态") == "现行有效")
        if 有效数:
            信号.append({"来源": f"状态现行有效({有效数}条)", "方向": "正面"})
    版本数 = sum(1 for e in 可验证 if e.get("版本警告"))
    if 版本数:
        危险信号 += 版本数
        信号.append({"来源": f"法条时效问题({版本数}条)", "方向": "负面"})
    if 疑似编造:
        危险信号 += len(疑似编造)
        信号.append({"来源": f"疑似编造法条({len(疑似编造)}条)", "方向": "负面"})

    溯源全部通过 = False
    if 溯源 and 溯源.get("items"):
        越界数 = sum(1 for item in 溯源["items"] if not item.get("有效"))
        if 越界数:
            危险信号 += 越界数
            信号.append({"来源": f"溯源越界({越界数}处)", "方向": "负面"})
        elif 溯源.get("引用数", 0) > 0:
            溯源全部通过 = True
            信号.append({"来源": "原文溯源全部验证", "方向": "正面"})

    # 未校验与覆盖不足：不是"错了"，是"本工具没说它对了" —— 封顶，不指控
    if 无条号数:
        信号.append({"来源": f"无条号援引，无法校验({无条号数}处)", "方向": "中性"})
    if 未识别数:
        信号.append({"来源": f"无法定位到具体法律({未识别数}处)", "方向": "中性"})
    if 案发未知:
        信号.append({"来源": "未提供案发日期，时效未校验", "方向": "中性"})
    if 覆盖不足数:
        信号.append({"来源": f"法条库未覆盖({覆盖不足数}条)", "方向": "中性"})

    质量问题数 = len(验证.get("问题", []))
    if 质量问题数:
        信号.append({"来源": f"质量问题({质量问题数}项)", "方向": "负面"})
    else:
        信号.append({"来源": "格式检查通过（只查字数，不构成内容证据）", "方向": "中性"})

    有证据 = bool(可验证) or 溯源全部通过
    if 危险信号:
        等级 = "低"
    elif 未校验数 or 案发未知 or 覆盖不足数 or 质量问题数 or not 有证据:
        等级 = "中"
    else:
        等级 = "高"

    return {"等级": 等级, "明细": 信号,
            "已校验数": 校验.get("已校验数", 0), "未校验数": 未校验数}
