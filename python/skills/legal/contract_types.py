def 判定类型(合同文本):
    """按特征词命中数给一个最可能类型；平票或全 0 → "通用"。

    ⚠️ 返回"通用"是有意的退路：拿一张错的必查表去报"缺条款"，比报少更坏。
    """
    文本 = 合同文本 or ""
    得分 = {类: sum(1 for 词 in 词表 if 词 in 文本) for 类, 词表 in 特征词.items()}
    最高 = max(得分.values()) if 得分 else 0
    if 最高 == 0:
        return "通用", 得分
    冠军 = [类 for 类, 分 in 得分.items() if 分 == 最高]
    if len(冠军) > 1:
        return "通用", 得分          # 平票不猜
    return 冠军[0], 得分


def 必查清单(类型):
    return 必查表.get(类型, 通用)
