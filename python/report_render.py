"""把七个维度的原始输出，合成**按条款读**的 Markdown 报告（＋一份法条原文附录）。

**两份，不是一个文件**（2026-09-28 用户拍板）：
  · `渲染(数据)`     —— **给人读的**：结论 + 逐条问题 + 缺什么/补什么 + 核对到什么程度
                        （实测 13,396 字）；
  · `渲染附录(数据)` —— **给人查证的**：报告引到的每一条法条原文（实测 9,591 字，占 42%）。
拆的理由：附录占了整份的四成，而它跟"读报告"是两种用法。合成一个文件时，
读的人在 42% 的条文里翻不到头；删掉又不该（那是证据）。

🔴 **为什么要合成**（2026-09-28 真机）：下载件原来是七个维度**原样拼接**，
跑出来一份 **32,338 字 / 554 行**的纯文本。实测那份报告里：

    · **24/24 条**被提到的条款，都在 **2~4 个维度**里各说了一遍
      （同一条「甲方可从工资扣款」，「哪些条款对你不利」「权利义务不对等的」
      「写得含糊的」三节各写一段 —— 同一件事、同一条法、只是分类角度不同）；
    · **「谈判顺序」5130 字**，是全文最长的一节 —— 而它本该是"汇总"，
      内容基本是前面几节的复述（它的**独有价值只有档位**：必须改 / 力争改 / 可接受）；
    · 而「能不能签 + 先改哪三条」那 **430 字**（`总结`）被压在 554 行的最后。

⇒ 收件人翻五百行、同一件事读三遍，还找不到结论。

**判断**：那七个维度是**生成时**的切法（并行跑、互相独立、每人一个角度），
**不是给人读的切法**。给人读要按**条款**重组：一个问题一段，
把它的风险、改法、依据、谈判档位写在一起。

⚠️ **去重是有代价的，如实记**：同一条款在几个维度里的说法**不完全一样**
（举的都是同一件事，但侧重不同）。这里的规则是**取正文最长的那个**
（信息最全的那一份），其余的丢弃 —— 所以**下载件是"合并可读版"，不是全量**。
**全量原始输出仍然在页面上**（七个维度各是一张卡）。
"""

from __future__ import annotations
import re


# ── 版式：**纯文本，一个标记符号都不许露给读者**（2026-09-28 用户实测反馈）──
#
# 🔴 我第一版输出的是 **Markdown**，理由写的是「微信、钉钉、各类编辑器都认得」——
#    **那句话是错的**：那些地方认得的是**聊天里发的 Markdown**；
#    而下载成**一个文件、在手机里打开**，`#` `**` `>` 全是**字面的噪音**。
#    用户的反馈原话：「一对符号文字对一起，我都看不下去」。
#    ⇒ 我验的是"这格式在某个地方能渲染"，**没验他实际是在哪儿读的**。
#
# ⇒ 版面改成：**任何手机、任何查看器打开都读得下去**
#    · 层级靠 **分隔线 + 缩进 + 空行**，不靠渲染器认得的标记；
#    · 长段落拆开：`问题 / 改成 / 依据` 各占一行，不挤成一坨；
#    · 标题两边留白，条目之间空一行。
#
# 这一节只做"把模型给的文字**洗干净**"，**不改写内容** ——
# 内容里本来就有的 `**`（模型爱加粗）也要去掉，别原样露出去。

_粗体 = re.compile(r"\*\*(.+?)\*\*", re.S)
_行内标记 = re.compile(r"(?m)^\s{0,3}#{1,6}\s*")


def _净(文本: str) -> str:
    """把模型文字里的标记洗掉：`**粗体**` → 粗体、行首的 `#` 去掉、压多余空行。

    ⚠️ **只洗标记，不改一个字** —— 这是法律文本，措辞不能被程序动。
    """
    s = _粗体.sub(r"\1", str(文本 or ""))
    s = _行内标记.sub("", s)
    s = re.sub(r"[ \t]+\n", "\n", s)
    return re.sub(r"\n{3,}", "\n\n", s).strip()


#: 正文里"建议：…"那一截 —— 单独起一行。它和前面的风险描述是两件事，
#: 挤在一句里在手机上就是一大坨（用户反馈的原话：「一对符号文字对一起」）。
_段中分点 = re.compile(r"\s*(?=(?:建议|理由|依据)[：:])")


def _分段(文本: str) -> str:
    """把「…。 建议：…」拆成两行。**只加换行，不改一个字。**"""
    return "\n".join(x.strip() for x in _段中分点.split(str(文本 or "")) if x.strip())


def _缩(文本: str, 空格: int) -> str:
    """整段缩进（含空行不缩，免得留一堆尾空格）。"""
    头 = " " * 空格
    return "\n".join((头 + l) if l.strip() else "" for l in str(文本 or "").splitlines())


_分隔 = "─" * 30
_重线 = "━" * 30


def _节(标题: str) -> list:
    """一条分隔线 + 缩进的标题（正文之前的"换章"记号）。"""
    return ["", _分隔, f"  {标题}", _分隔, ""]



import re
from datetime import date

# ── 各维度在合成件里的去处 ────────────────────────────────────────
#: 这三个是**同一层**：都在描述"这条有什么问题"，只是分类角度不同 ⇒ 合并成一条。
问题维度 = ("风险清单", "失衡条款", "歧义表述")
#: 缺什么 + 怎么补：前者有条款锚点、后者没有（它给的是还不存在的文字），
#: **没法可靠配对**（条数不一定相等，按序配会把建议挂到错的地方）⇒ 分两节保留。
缺什么维度 = "缺失条款"
补什么维度 = "新增条款"
改法维度 = "改法建议"
档位维度 = "谈判顺序"
结论文本 = "总结"


# `- 【第十条第3款】「摘录」 风险：…` —— 条目以行首的锚点开始
_条目头 = re.compile(r"^- 【([^】]+)】")
# 档位标题：`## 第一档：必须改（不改就不该签）`
_档位头 = re.compile(r"^#{2,3}\s*第[一二三四五六七八九十]+档[：:]\s*([^（(\n]+)")
# `- 【第十条第3款】「…」 改成：「…」` —— 改法那一维
_改成 = re.compile(r"改成：「(.+?)」", re.S)
_依据 = re.compile(r"依据：\s*([^\n]+)")
_摘录 = re.compile(r"「(.+?)」", re.S)


def 拆条目(文本: str) -> list[tuple[str, str, str]]:
    """把一维的输出拆成 `[(档位, 条款号, 整段文字)]`。

    ⚠️ **空行是条目的边界**：模型每条之间空一行，而一条内部（风险/建议/依据）
    是不换行的长句。所以按空行切、按行首锚点认，两种写法都兜得住。
    ⚠️ 没有锚点的段落（比如模型没守格式）**不丢** —— 挂到 `""` 号上，渲染时进"其他"。
    """
    出: list[tuple[str, str, str]] = []
    档 = ""
    当前: list | None = None

    def 收尾():
        nonlocal 当前
        if 当前:
            段 = 当前[1].strip()
            if 段:
                出.append((档, 当前[0], 段))
            当前 = None

    for 行 in (文本 or "").splitlines():
        m档 = _档位头.match(行)
        if m档:
            收尾()
            档 = m档.group(1).strip()
            continue
        m头 = _条目头.match(行)
        if m头:
            收尾()
            当前 = [m头.group(1), 行]
        elif 当前 is not None:
            if 行.strip():
                当前[1] += "\n" + 行
            else:
                收尾()
        elif 行.strip() and not 行.startswith("#") and not 行.startswith(">"):
            # 没有锚点的裸段落：留着，别吞
            当前 = ["", 行]
    收尾()
    return 出


def _取摘录(段: str) -> str:
    m = _摘录.search(段)
    return (m.group(1).strip() if m else "")


#: 行首那截 `- 【第十条第3款】「原文摘录」` —— 标题里已经写过了，正文里要拿掉
_前缀 = re.compile(r"^- 【[^】]+】\s*(「.*?」)?\s*", re.S)
#: 正文开头的 `风险：` —— 外面已经有 `**问题**：` 这个标签了
_开标签 = re.compile(r"^(风险|问题)[：:]\s*")
#: 正文结尾的 `依据：…` —— 外面单独有一行 `**依据**：`，留着就是同一句话说两遍。
#: ⚠️ **不能写成 `依据：《[^》]+》$`**：法条的写法是 `《劳动合同法》第85条`，
#: `第85条` 在 `》` **之后** ⇒ 那个正则一条都匹配不上（第一版就是这么错的）。
_尾依据 = re.compile(r"\s*依据[：:][^\n]*$")


def _去前缀(段: str) -> str:
    """把 `- 【号】「摘录」 风险：…` 变成 `风险：…`。

    ⚠️ **不去掉就等于同一句话说两遍**：渲染出来的标题是
    `### 第十条第3款 ｜ 甲方有权依法追责并扣除相应损失费用`，
    正文第一行又原样重复一遍 `- 【第十条第3款】「甲方有权依法追责…」 风险：…`。
    """
    出 = _前缀.sub("", 段, count=1).strip()
    出 = _开标签.sub("", 出, count=1)
    出 = _尾依据.sub("", 出).strip()
    return 出


def 合并(数据: dict) -> dict:
    """→ `{"按条款": {号: {...}}, "顺序": [...], "档位表": {...}, ...}`"""
    按条款: dict[str, dict] = {}
    顺序: list[str] = []

    def 拿(号: str) -> dict:
        if 号 not in 按条款:
            按条款[号] = {"号": 号, "摘录": "", "问题": [], "改法": "", "依据": "", "档位": "",
                          "出处": []}
            顺序.append(号)
        return 按条款[号]

    # ① 三个"有什么问题"的维度：先各自收一份，后面按号取最长的
    for 名 in 问题维度:
        for _档, 号, 段 in 拆条目(数据.get(名) or ""):
            if not 号:
                continue
            条 = 拿(号)
            条["问题"].append((len(段), 名, 段))
            条["摘录"] = 条["摘录"] or _取摘录(段)
            条["出处"].append(名)

    # ② 改法：独有的替换文字，必须留
    for _档, 号, 段 in 拆条目(数据.get(改法维度) or ""):
        if not 号:
            continue
        条 = 拿(号)
        m = _改成.search(段)
        if m:
            条["改法"] = m.group(1).strip()
        条["摘录"] = 条["摘录"] or _取摘录(段)
        条["出处"].append(改法维度)

    # ③ 谈判档位：这一维**只有档位有价值**，正文基本是复述
    for 档, 号, 段 in 拆条目(数据.get(档位维度) or ""):
        if not 号:
            continue
        条 = 拿(号)
        条["档位"] = 条["档位"] or 档
        if not 条["问题"]:
            # ⚠️ 只在这一维出现过的条款（前三个维度都没提）⇒ **不能丢**，
            #    把"为什么重要"当问题收下。
            条["问题"].append((len(段), 档位维度, 段))
            条["出处"].append(档位维度)

    # ④ 依据：从各段里顺出来的第一条（上面几个维度都会写）
    for 号, 条 in 按条款.items():
        for _长度, _名, 段 in sorted(条["问题"], reverse=True):
            m = _依据.search(段)
            if m:
                条["依据"] = m.group(1).strip()
                break
        # 取正文最长的那一份当"问题"，其余丢弃（见模块头"去重是有代价的"）
        条["问题"].sort(key=lambda x: -x[0])
        条["摘录"] = 条["摘录"] or (_取摘录(条["问题"][0][2]) if 条["问题"] else "")
        条["正文"] = _去前缀(条["问题"][0][2]) if 条["问题"] else ""
        条["其余出处"] = [名 for _l, 名, _d in 条["问题"][1:]]

    return {"按条款": 按条款, "顺序": 顺序,
            "缺什么": 拆条目(数据.get(缺什么维度) or ""),
            "补什么": 拆条目(数据.get(补什么维度) or ""),
            "结论": (数据.get(结论文本) or "").strip()}


#: 「补什么」那一条的写法：`补什么风险：…` 换行 `条款文字：「…」`
_补风险 = re.compile(r"补什么风险[：:]\s*(.+?)(?=\n条款文字|$)", re.S)
_补文字 = re.compile(r"条款文字[：:]\s*「(.+?)」", re.S)


def 拆补充条款(段: str) -> tuple[str, str]:
    """→ (它补的是什么风险, 可直接粘贴的条款文字)。"""
    风 = _补风险.search(段)
    文 = _补文字.search(段)
    return ((风.group(1).strip() if 风 else ""),
            (文.group(1).strip() if 文 else ""))


#: 档位排序：必须改在前。认不出的排最后。
_档位序 = {"必须改": 0, "力争改": 1, "可接受": 2}


def _档位排名(档: str) -> int:
    for 键, 值 in _档位序.items():
        if 键 in (档 or ""):
            return 值
    return 9


def 有附录(数据: dict) -> bool:
    """有没有"核到的法条原文"可出。没有就别给第二个下载按钮。"""
    return bool(数据.get("法条统计")) or bool(数据.get("法条对照")) or bool(
        (数据.get("溯源") or {}).get("items") if isinstance(数据.get("溯源"), dict) else False)


def _附录节(数据: dict) -> list[str]:
    """「核到的法条原文」那一段（**原始证据，不参与去重**）。

    🔴 实测 **9,591 字**，占合并后整份下载件的 **42%** —— 它是整个文件里最大的一块。
    但报告里每条结论都引了法条，收件人（尤其律师）要能当场看见原文 ⇒ **不能删**。
    ⇒ 2026-09-28 起**拆成单独一份下载**（`渲染附录`）：想读报告的人拿到的是 13,396 字，
      要查证的人另拿这一份。**一份给人读、一份给人查**，接缝就在这儿。
    """
    附: list[str] = []
    法统 = 数据.get("法条统计")
    if 法统:
        附.append(str(法统))
    for 条目 in (数据.get("法条对照") or []):
        if not isinstance(条目, dict):
            continue
        尾 = []
        if 条目.get("施行日期"):
            尾.append(f"施行: {条目['施行日期']}")
        if 条目.get("取代"):
            尾.append(str(条目["取代"]))
        附.append(f"**{条目.get('法名', '')}** {条目.get('引用', '')}"
                  f"（{条目.get('状态') or '状态未知'}）"
                  + (f" · {' · '.join(尾)}" if 尾 else "")
                  + f"\n\n{条目.get('条文', '')}")
    溯源 = 数据.get("溯源") if isinstance(数据.get("溯源"), dict) else {}
    for item in (溯源.get("items") or []):
        标 = "" if item.get("有效") else "⚠️ 原文里没有这一段："
        附.append(f"{标}原文第{item.get('段号', '')}段：\n\n{item.get('内容', '')}")
    return 附


def 渲染附录(数据: dict) -> str:
    """法条原文那一份（单独下载）。**纯文本**，同上。"""
    名称 = (数据.get("判例名") or "未命名").strip()
    出 = [_重线, "   法条原文", f"   {名称}", _重线, "",
          "  这是分析报告的附录：报告里引到的每一条法律，原文照录。", ""]
    附 = _附录节(数据)
    if not 附:
        出 += ["  （这一份没有引到可核对的法条。）", ""]
        return "\n".join(出) + "\n"
    for 块 in 附:
        出 += [_分隔, ""] + _缩(_净(块), 2).splitlines() + [""]
    出 += ["", _重线, "",
           "  条文照录自本地法条库，不做解释、不判断它适不适用。",
           "  真要签字或真要打官司之前，请带原件找执业律师核实。", ""]
    return "\n".join(出) + "\n"


def 渲染(数据: dict) -> str:
    """给人读的那一份。**纯文本** —— 见模块头「版式」那一节。"""
    合 = 合并(数据)
    按条款, 顺序 = 合["按条款"], 合["顺序"]
    名称 = (数据.get("判例名") or "未命名").strip()

    出 = [_重线, "   法律分析报告", f"   {名称}", _重线, ""]

    # ── 抬头：第一屏就说清"站在谁的角度、核到什么程度" ──
    立场 = str(数据.get("立场") or "").strip()
    if 立场:
        出.append("   立场" + " " * 8 + ("中立（不预设你是哪一方）" if 立场 == "中立"
                                        else f"站在【{立场}】角度"))
    等级 = 数据.get("等级")
    if 等级:
        出.append("   可信度" + " " * 6 + f"{等级}")
    if 数据.get("覆盖度") is not None:
        出.append("   核对覆盖" + " " * 4 + f"{round(数据['覆盖度'] * 100)}%")
    核 = 数据.get("核验读数") or {}
    if 核:
        出 += ["", f"   依据共 {核.get('引用总数', '?')} 处："
                   f"逐条核到原文 {核.get('核到', 0)} 处、"
                   f"对不上 {核.get('对不上', 0)} 处、"
                   f"没法核 {核.get('没法核', 0)} 处。"]
    出.append("")

    # ── 结论：全文最该被读到的四百字，放最前 ──
    结论 = _净(合["结论"])
    if 结论:
        出 += _节("结论")
        # 总结里模型爱用 `**一、xxx**` 当小标题 —— 洗掉标记之后按它切开分段，
        # 不然四百字挤成一坨（手机上正好是最难读的那种）
        for 块 in re.split(r"(?m)^\s*(?=[一二三四五六七八九十]+、)", 结论):
            块 = 块.strip()
            if 块:
                出 += _缩(块, 3).splitlines() + [""]

    # ── 逐条问题：一条款一条，谈判档位在前 ──
    有条 = [按条款[号] for 号 in 顺序 if 按条款[号].get("正文") or 按条款[号].get("改法")]
    有条.sort(key=lambda 条: (_档位排名(条.get("档位") or ""), 顺序.index(条["号"])))
    if 有条:
        出 += _节(f"逐条问题（{len(有条)} 条）")
        for i, 条 in enumerate(有条, 1):
            出 += [f"  {i}) {条['号']}"]
            摘 = _净(条.get("摘录") or "")
            if 摘:
                出 += _缩(摘[:60] + ("…" if len(摘) > 60 else ""), 6).splitlines()
            出.append("")
            if 条.get("档位"):
                出 += _缩(_净(f"谈判档位：{条['档位']}"), 6).splitlines()
            if 条.get("正文"):
                出 += _缩(_净(f"问题：{_分段(条['正文'])}"), 6).splitlines()
            if 条.get("改法"):
                出 += ["", "      【改 成】"] + _缩(_净(条["改法"]), 6).splitlines()
            if 条.get("依据"):
                出 += ["", "      【依 据】"] + _缩(_净(条["依据"]), 6).splitlines()
            出 += ["", _分隔]

    # ── 缺什么 / 补什么：没有可合并的键，分两节 ──
    if 合["缺什么"]:
        出 += _节("合同里没写的")
        for _档, 号, 段 in 合["缺什么"]:
            出 += [f"  ● {号 or '（未编号）'}", ""]
            出 += _缩(_净(_去前缀(段)), 6).splitlines() + [""]
    if 合["补什么"]:
        出 += _节("缺的条款，补这么写")
        for _档, _号, 段 in 合["补什么"]:
            风险, 文字 = 拆补充条款(段)
            标 = re.split(r"[，。；,;]", _净(风险), maxsplit=1)[0][:34] or "补充条款"
            出 += [f"  ● {标}", ""]
            if 风险:
                出 += _缩(_净(f"补什么风险：{风险}"), 6).splitlines() + [""]
            if 文字:
                出 += ["      【条款文字】"] + _缩(_净(文字), 6).splitlines() + [""]

    # ── 工具自己没把握的部分，放在正文之后、免责之前 ──
    for 标题, 键 in (("要你人去核实的", "待核实"), ("本工具的覆盖边界（不代表结论有误）", "工具边界")):
        列 = [_净(x) for x in (数据.get(键) or []) if str(x).strip()]
        if 列:
            出 += _节(标题)
            for x in 列:
                出 += _缩(f"· {x}", 3).splitlines() + [""]

    出 += ["", _重线, "",
           "  本报告由「判例助手」自动生成"
           f" ｜ {数据.get('日期') or date.today()}",
           "",
           "  它做的事情只有一件：把报告里引用的每一条法律、",
           "  每一段合同原文拿回去逐字核对。",
           "  它没有判断法律结论对不对，也看不到你手上的完整材料。",
           "",
           "  真要签字或真要打官司之前，请带原件找执业律师核实。", ""]
    return "\n".join(出) + "\n"
