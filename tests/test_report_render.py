import os
import sys

os.environ.setdefault("DATA_DIR", "/tmp/判例助手-合成测试-不会写盘")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "python"))

from report_render import 渲染, 渲染附录, 有附录, 合并, 拆条目  # noqa: E402

# 一条款、三个维度各说一遍 —— 复刻真机的形状（同一件事、同一条法、分类角度不同）
风险清单 = ('- 【第十条第3款】「甲方有权扣除损失费用」 风险：扣款无上限，'
          '易被认定克扣工资。 建议：加上限。依据：《劳动合同法》第85条。')
失衡条款 = ('- 【第十条第3款】「乙方擅自离职……甲方有权依法追责并扣除相应损失费用」 '
          '风险：该款授权甲方扣款但未限定比例和程序，工资除法定代扣外不得随意扣除，'
          '自行扣款易被认定克扣工资。建议：改为依法另行追偿。依据：《劳动合同法》第85条。')
歧义表述 = ('- 【第十条第3款】「扣除相应损失费用」 风险："损失费用"没有计算标准。'
          '依据：实务判断（法律未强制）。')
改法建议 = ('- 【第十条第3款】「乙方擅自离职……」 改成：「甲方可依法向乙方追偿，'
          '不得直接从工资中扣除。」 理由：加上限。依据：《劳动合同法》第85条。')
谈判顺序 = ('## 第一档：必须改（不改就不该签）\n\n'
          '- 【第十条第3款】「甲方有权扣除损失费用」 为什么重要：直接扣款即违法。'
          '用哪份改法文字去提：用【改法建议】第十条第3款。')
缺失条款 = '- 【第九条】「按法律法规执行」 风险：没写经济补偿的情形。依据：《劳动合同法》第46条。'
新增条款 = ('补什么风险：没写经济补偿的计算方式。\n'
          '条款文字：「甲方应按工作年限每满一年支付一个月工资。」')
总结 = '**一、能不能签** 风险量级：高。**二、先解决** 1. 第十条第3款。**三、退路** 不签。'

数据 = {
    "判例名": "测试合同", "立场": "甲方",
    "风险清单": 风险清单, "失衡条款": 失衡条款, "歧义表述": 歧义表述,
    "改法建议": 改法建议, "谈判顺序": 谈判顺序,
    "缺失条款": 缺失条款, "新增条款": 新增条款, "总结": 总结,
    "等级": "低", "覆盖度": 0.88,
    "核验读数": {"引用总数": 10, "核到": 8, "对不上": 1, "没法核": 1, "库外": 0},
    "待核实": ["报告里写的你合同第十二条，在你的原文里对不上"],
    "工具边界": ["『缺的条款，补这么写』那一维没有原文可逐字比对"],
    "法条统计": "引用法条 2 条",
    "法条对照": [{"法名": "劳动合同法", "引用": "《劳动合同法》第85条",
                "状态": "现行有效", "施行日期": "2013-07-01", "条文": "第八十五条 用人单位……"}],
    "溯源": None,
}


def test_同一条款在多个维度里只出现一次():
    """🔴 **这条是"东西太多"的正解**：真机上 24/24 条都在 2~4 个维度里各说一遍。

    判据钉的是**标题层**：`### 第十条第3款` 只许出现一次。
    """
    文 = 渲染(数据)
    assert 文.count("### 第十条第3款") == 1, \
        f"同一条款被拆成了多个标题 ⇒ 又变成「同一件事说三遍」：\n{文}"


def test_三个维度里说的那句话只能留一句():
    """去重取**正文最长的那个**（信息最全）。三个输入的正文都在，说明没生效。"""
    合 = 合并(数据)
    条 = 合["按条款"]["第十条第3款"]
    assert len(条["问题"]) == 3, f"应该收集到 3 份候选，实际 {len(条['问题'])}"
    assert "未限定比例和程序" in 条["正文"], "留下的不是信息最全的那一份"
    文 = 渲染(数据)
    assert "扣款无上限，易被认定克扣工资" not in 文, "短的那两份没被丢掉"
    assert "没有计算标准" not in 文, "短的那两份没被丢掉"


def test_改法文字和档位要留下来():
    """这两样是**别的维度没有的**：改法是可直接粘贴的文字，档位决定先做哪几条。"""
    文 = 渲染(数据)
    assert "甲方可依法向乙方追偿" in 文, "改法文字被去重去掉了 —— 那是这一维唯一的价值"
    assert "**谈判档位**：必须改" in 文, "谈判档位没带上"
    assert "《劳动合同法》第85条" in 文, "依据没带上"


def test_结论要排在正文之前():
    """真机上「能不能签 + 先改哪三条」被压在 554 行的**最后**，等于没写。"""
    文 = 渲染(数据)
    assert "## 结论" in 文, "结论那一节整个没了"
    assert "## 逐条问题" in 文, "逐条问题那一节没了"
    assert 文.index("## 结论") < 文.index("## 逐条问题"), "结论被排到正文后面去了"
    assert 文.index("风险量级：高") < 文.index("## 逐条问题")


def test_法条原文必须还在_只是挪到了附录那一份():
    """🔴 附录实测 **9,591 字**（占合并后整份的 42%）—— 做"去重"时最容易顺手删掉。
    它是**证据**，不是分析，不参与去重。

    2026-09-28 拆成两份：主报告给人读、附录给人查证。**拆分不等于可以丢。**
    """
    附文 = 渲染附录(数据)
    assert "第八十五条 用人单位……" in 附文, "法条原文没了 —— 那是收件人查证的依据"
    assert "第八十五条" in 附文
    assert 有附录(数据) is True, "明明有法条却说不该出附录 ⇒ 前端那个按钮不会显示"
    # 反方向：没引到法条的输入，不该说"有附录"
    assert 有附录({"判例名": "空"}) is False
    assert 有附录({"判例名": "空", "法条对照": []}) is False


def test_两份各管一件事_主报告里不带附录():
    """拆分的意思就是**读的人在主报告里翻不到头**。附录又混回去 = 白拆。"""
    主 = 渲染(数据)
    assert "第八十五条 用人单位……" not in 主, "附录条文混回主报告了"
    assert "## 结论" in 主 and "## 逐条问题" in 主


def test_抬头要有立场和核验读数():
    文 = 渲染(数据)
    抬头 = 文.split("## 结论")[0]
    assert "甲方" in 抬头, "抬头没写站在谁的角度"
    assert "逐条核到原文" in 抬头, "抬头没写核到什么程度"


def test_缺什么补什么各自成节而且有小标题():
    """这两样**没有可合并的键**（补的那一维连条款号都没有），所以分两节 ——
    但各自必须有小标题，否则就是两万字的墙，跟没整理一样。"""
    文 = 渲染(数据)
    assert "## 合同里没写的" in 文 and "### 第九条" in 文
    assert "## 缺的条款，补这么写" in 文 and "**条款文字**" in 文


def test_拆条目_空行分条_不吞没锚点的段落():
    """模型没守格式（没挂锚点）时**不能吞掉** —— 它是"未校验"，不是"不存在"。"""
    段 = "开头一句没锚点的话。\n\n- 【第三条】「x」 风险：y。\n\n- 【第五条】「z」 风险：w。"
    出 = 拆条目(段)
    assert any(号 == "" for _档, 号, _d in 出), f"没锚点的段落被吞了：{出}"
    assert [号 for _档, 号, _d in 出 if 号] == ["第三条", "第五条"]


