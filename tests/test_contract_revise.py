"""改动对照表的回归：**原文要取整行、省略号要认、定位不了不许编**。

来历（2026-09-28）：本来做的是「自动改好的合同」，跑真机数据当场露馅 ——
同一句话出现两遍。根因是**分析输出本身的格式不匹配**：

    「摘录」17~30 字（行里一小截）· 「改成」115~179 字（整条重写）
    ⇒ 拿一小截去换一整条，开头必然重复

⚠️ 我第一版验的是「12/12 字面命中」（**找不找得到**），不是「改完读不读得通」。
⇒ 修订版已删，只出对照表。这个文件钉的就是**对照表为什么能出、修订版为什么不能**。

跑法：python3 -m pytest tests/ -q
"""
import os
import sys

os.environ.setdefault("DATA_DIR", "/tmp/判例助手-对照表测试-不会写盘")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "python"))

from contract_revise import 对照, 渲染对照表, _找那一行  # noqa: E402

原文 = "\n".join([
    "第一条 试用期自______年____月____日起至______年____月____日止。",
    "第二条 工作岗位",
    "3、甲方可根据生产经营需要调整乙方工作岗位、工作内容，调整前应提前告知乙方，乙方无正当理由应当服从合理工作安排。",
    "第十条 违约责任",
    "2、乙方违反本合同约定给甲方造成经济损失的，应当根据损失程度依法承担赔偿责任。",
    "2、另一款也提乙方违反本合同约定给甲方造成经济损失。",
])

数据 = {
    "判例名": "测试合同", "立场": "甲方",
    "风险清单": '- 【第二条第3款】「乙方无正当理由应当服从合理工作安排」 风险：单方调岗。依据：《劳动合同法》第35条。',
    # ⚠️ 带省略号的摘录 —— 提示词**明确允许**「中间可用……省略」
    "改法建议": ("- 【第二条第3款】「甲方……调整乙方工作岗位、工作内容，调整前应提前告知乙方」 "
              "改成：「甲方调整乙方工作岗位须经双方协商一致并签订书面变更协议。」 理由：协商一致。"
              "依据：《劳动合同法》第35条。"),
    "新增条款": "补什么风险：没约定经济补偿。\n条款文字：「甲方应按工作年限每满一年支付一个月工资。」",
}


def test_原文取的是整行_不是那一小截摘录():
    """🔴 对照表里「原文」要是**那一行的全文**。

    取摘录（17 字）的话，「原文 → 改成」看着像"改一点变成一大段"，读者对不上。
    """
    果 = 对照(原文, 数据)
    条 = [c for c in 果["对照"] if c["号"] == "第二条第3款"][0]
    assert 条["定位准"] is True
    assert 条["原"].startswith("3、甲方可根据生产经营需要调整"), f"取的不是整行：{条['原']!r}"
    assert 条["原"].endswith("服从合理工作安排。"), f"行被切了：{条['原']!r}"


def test_摘录带省略号也要能定位():
    """🔴 `引用格式要求` 明写「摘录必须能逐字找到（**中间可用……省略**）」——
    所以带省略号的摘录是**合法写法**。拿整串做 `in` 检查，一条都定位不到
    （第一版就是这么把一条真的判成"没定位"的）。

    判据：按 `……` 切开，**每一段都落在同一行**才算命中。
    """
    行, 准 = _找那一行(原文, "甲方……调整乙方工作岗位、工作内容，调整前应提前告知乙方")
    assert 准, "带省略号的摘录定位失败"
    assert "调整乙方工作岗位" in 行


def test_定位不唯一就退回摘录_并明说():
    """🔴 **不许编一个"看着像"的原文**：命中两行时退回摘录，并把"没定位准"标出来 ——
    编出来读者会以为那就是原文。"""
    行, 准 = _找那一行(原文, "乙方违反本合同约定给甲方造成经济损失")
    assert 准 is False, "命中了 2 行却说定位准"


def test_对照表要标出没定位的那几处():
    文 = 渲染对照表(原文, 数据)
    assert "原  文" in 文 and "改 成" in 文
    assert "依  据" in 文, "依据没带上"
    assert "建议新增" in 文, "新增条款那一节没了"


def test_对照表里不许出现_自动改好的合同():
    """🔴 **钉住"修订版已删"这个决定**：它写出来的合同同一句话出现两遍。
    谁要是哪天又把它加回来，这条会红。"""
    import contract_revise as C
    assert not hasattr(C, "渲染修订版"), "修订版又回来了 —— 先读模块头，那个格式现在做不出能用的"
    assert not hasattr(C, "修订"), "同上"
    文 = 渲染对照表(原文, 数据)
    # 对照表是"原文/改成"并列，**不是**成品合同：全文里不该直接出现"改好的合同"这种说法
    assert "按分析改过的版本" not in 文


if __name__ == "__main__":
    import pytest
    sys.exit(pytest.main([__file__, "-q"]))
